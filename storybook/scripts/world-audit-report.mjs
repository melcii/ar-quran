#!/usr/bin/env node
// The world audit report: one entry per surah, from
//  - content/worlds/validation.json      fast validator (npm run worlds:validate)
//  - content/worlds/browser-results.json browser checks, collected here from
//                                        scripts/physics/out/ when it exists
//  - content/worlds/audit-findings.json  findings, causes, fixes and statuses
// Writes docs/WORLD-AUDIT.md. Usage: npm run worlds:report
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const J = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const SUR = J('content/quran/surahs.json');
const val = J('content/worlds/validation.json');
const find = J('content/worlds/audit-findings.json');

// Collect browser results (keeps earlier ones for worlds not re-run).
const brPath = join(root, 'content/worlds/browser-results.json');
const br = existsSync(brPath) ? JSON.parse(readFileSync(brPath, 'utf8')) : { worlds: {} };
const outDir = join(root, 'scripts/physics/out');
const parse = (f) => {
  try {
    const s = readFileSync(join(outDir, f), 'utf8').trim();
    return s ? JSON.parse(s.slice(s.indexOf('{'))) : null;
  } catch {
    return null;
  }
};
if (existsSync(outDir)) {
  const day = new Date().toISOString().slice(0, 10);
  for (const f of readdirSync(outDir)) {
    let m;
    if ((m = f.match(/^v-(\w+)-(desktop|phone)\.json$/))) {
      const r = parse(f);
      if (!r) continue;
      const L = r.live ?? {};
      const fails = [];
      if (!r.report?.ok) fails.push('collision validator');
      if (r.audit?.uncoveredN) fails.push(`${r.audit.uncoveredN} drawn parts without collider`);
      if (L.inside) fails.push(`inside a solid ${L.inside} frames`);
      if (L.under) fails.push(`under the ground ${L.under} frames`);
      if (L.camInside) fails.push(`camera inside a solid at ${L.camInside} of 8 angles`);
      if (L.camUnder) fails.push('camera under the ground');
      if (L.maxScaleDev > 1e-6) fails.push(`explorer scale changed by ${L.maxScaleDev}`);
      if (L.safeOk === false) fails.push('return to safe ground lost progress');
      if (r.errors?.length) fails.push(`page errors: ${r.errors.slice(0, 2).join('; ')}`);
      ((br.worlds[m[1]] ??= {})[`validate_${m[2]}`] = { date: day, pass: !fails.length, fails });
    } else if ((m = f.match(/^p-(\w+)\.json$/))) {
      const r = parse(f);
      if (!r) continue;
      const fails = [];
      if (!r.allDone) fails.push('not every activity could be finished');
      if (r.forced?.length) fails.push(`finished by the test, not by play: ${r.forced.join(', ')}`);
      if (r.unwalkable?.length) fails.push(`no walking route to: ${[...new Set(r.unwalkable.map((u) => u.task))].join(', ')}`);
      if (!r.savedAfterReload) fails.push('progress lost after reload');
      if (r.midResume && !r.midResume.doneKept) fails.push('progress lost when leaving halfway');
      if (r.midResume && r.midResume.placeKeptM > 3) fails.push(`came back ${r.midResume.placeKeptM} m from where they left`);
      if (r.leaveOk === false) fails.push(`leaving the world failed ${r.leaveErr ?? r.leaveTo ?? ''}`);
      if (r.errors?.length) fails.push(`page errors: ${r.errors.slice(0, 2).join('; ')}`);
      ((br.worlds[m[1]] ??= {}).play = { date: day, pass: !fails.length, fails, secs: r.secs, resume: r.midResume, leaveTo: r.leaveTo });
    }
  }
  for (const [f, k] of [['ark-checks.json', 'ark_checks'], ['ark-animals.json', 'ark_animals']]) {
    const r = parse(f);
    if (r) (br.worlds.ark ??= {})[k] = { date: day, result: r };
  }
  writeFileSync(brPath, JSON.stringify(br, null, 1));
}

const L = [];
const vBy = Object.fromEntries(val.results.map((r) => [r.surah, r]));
const statusOf = (n) => {
  const items = find.surahs[String(n)] ?? [];
  const v = vBy[n];
  const b = br.worlds[String(n)] ?? {};
  const open = items.filter((i) => i.status === 'Issue Found');
  const errs = v?.counts.error ?? 1;
  const browserPass = b.validate_desktop?.pass;
  const playPass = b.play?.pass;
  if (errs || browserPass === false || playPass === false) return 'Issue Found';
  if (items.some((i) => i.status === 'Fix Implemented') && browserPass == null) return 'Fix Implemented';
  if (browserPass && (playPass ?? true) && !open.length) return 'Verified (automated)';
  return 'Retested';
};

L.push('# Quran Adventure: world audit, all 114 surahs');
L.push('');
L.push(`Generated by \`npm run worlds:report\` on ${new Date().toISOString().slice(0, 10)}. Fast validator run: ${val.date}. Nothing here is a scholar's review; every world is **Awaiting Content Review**.`);
L.push('');
L.push('Status columns: **Technical** is Issue Found, Fix Implemented (changed, not re-checked in the browser yet), Retested (the fast validator passes), or Verified (automated) (fast validator and the browser checks pass, in headless Chromium, never on a real phone or by a person). **Content** is Awaiting Content Review for every world until a named scholar reviews it.');
L.push('');
L.push('## How each world was checked');
L.push('');
L.push('- **Fast validator** (`npm run worlds:validate`, all 114, about 15 s a world): builds the same land and Rapier collision space as the game, then checks the spawn, every solid from eight sides, slopes, the edge, every footpath walked both ways, that every activity spot can be walked to from the start through story doors (start state and finished state), scenery on activity spots, rocks without colliders, herds, the task graph (prerequisites, loops, story order), ayah references, wording that makes the player a prophet or depicts anyone, and adaptation notes.');
L.push('- **Browser validator** (`scripts/physics/validate-world.js`): drawn parts without colliders, the same collision checks with the props that only exist when drawn, then live keyboard walking into the nearest solids, the camera from eight angles, explorer scale every frame, and Return to safe ground.');
L.push('- **Play-through** (`scripts/physics/play-world.js`, selected worlds): every activity finished through the game\'s own actions, a walking route checked before each move, leave and come back halfway, reload at the end, and Leave this world.');
L.push('- **Ark** (`ark-checks.js`, `ark-animals.js`): giraffes under the lintel, ramp rails, door while the ramp is up, the floor lifting with the flood, and each animal kind boarded on its own.');
L.push('');
L.push('## Summary');
L.push('');
L.push('| # | Surah | World | Technical | Content | Fast validator | Browser (desktop) | Phone | Play-through | Findings |');
L.push('|---|---|---|---|---|---|---|---|---|---|');
for (let n = 1; n <= 114; n++) {
  const v = vBy[n];
  const b = br.worlds[String(n)] ?? {};
  const items = find.surahs[String(n)] ?? [];
  const fv = v ? (v.counts.error ? `${v.counts.error} errors` : 'pass') + (v.counts.warn ? `, ${v.counts.warn} warnings` : '') : 'not run';
  const cell = (x) => (x == null ? 'not run' : x.pass ? `pass (${x.date})` : `FAIL: ${x.fails.join('; ')}`);
  L.push(`| ${n} | ${SUR[n - 1].nameTransliterated} | ${v?.name ?? '—'} | ${statusOf(n)} | Awaiting Content Review | ${fv} | ${cell(b.validate_desktop)} | ${cell(b.validate_phone)} | ${cell(b.play)} | ${items.length} |`);
}
L.push('');
L.push('## Engine-wide findings');
L.push('');
for (const f of find.all) {
  L.push(`### ${f.id}: ${f.status}`);
  L.push(`- **Issue:** ${f.issue}`);
  if (f.cause) L.push(`- **Root cause:** ${f.cause}`);
  if (f.fix) L.push(`- **Fix:** ${f.fix}`);
  L.push('');
}
L.push('## Per-surah reports');
L.push('');
for (let n = 1; n <= 114; n++) {
  const v = vBy[n];
  const b = br.worlds[String(n)] ?? {};
  const items = find.surahs[String(n)] ?? [];
  L.push(`### ${n}. ${SUR[n - 1].nameTransliterated} — ${v?.name ?? 'no world'}`);
  L.push('');
  L.push(`Technical: **${statusOf(n)}** · Content: **Awaiting Content Review** · ${v?.tasks ?? 0} activities, ${v?.spots ?? 0} places checked for walking, ${v?.solids ?? 0} solids pushed, ${v?.pathsWalked ?? 0} m of footpath walked.`);
  L.push('');
  if (items.length) {
    for (const i of items) L.push(`- **${i.status}** (${i.kind}): ${i.issue}${i.cause ? ` *Cause:* ${i.cause}` : ''}${i.fix ? ` *Fix:* ${i.fix}` : ''}`);
  }
  const rest = (v?.issues ?? []).filter((i) => i.level !== 'info');
  if (rest.length) for (const i of rest) L.push(`- Validator ${i.level} (${i.check}): ${i.msg}${i.at ? ` at ${JSON.stringify(i.at)}` : ''}`);
  const cross = (v?.issues ?? []).find((i) => i.level === 'info' && i.check === 'refs');
  if (cross) L.push(`- Note: ${cross.msg}.`);
  for (const k of ['validate_desktop', 'validate_phone', 'play']) if (b[k]) L.push(`- Browser ${k.replace('_', ' ')}: ${b[k].pass ? 'pass' : `FAIL: ${b[k].fails.join('; ')}`} (${b[k].date})`);
  if (!items.length && !rest.length) L.push('- No issue found by the checks above. Not played by a person.');
  L.push('');
}
if (br.worlds.ark) {
  L.push('### Nuh\'s Ark (inside Surah Hud, 11:37-44)');
  L.push('');
  L.push('```json');
  L.push(JSON.stringify(br.worlds.ark, null, 1).slice(0, 6000));
  L.push('```');
}
writeFileSync(join(root, 'docs/WORLD-AUDIT.md'), L.join('\n') + '\n');
console.log('Wrote docs/WORLD-AUDIT.md');
