// Imports the canonical Quran text and translation into content/quran/.
//
// Nothing here is written by hand or by a model: every verse is copied verbatim
// from the pinned npm packages below, cross-checked against an independent
// copy, and fingerprinted. Run `npm run validate` afterwards.
//
//   npm run import:quran
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { Mushaf } from "@quran.ws/text";
import { meta, getSurahMeta } from "quran-meta/hafs";
import { skeleton, stripEndPunctuation } from "./lib/compare.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "content", "quran");
const pkgDir = (name) => join(root, "node_modules", name);
const pkgFile = (name, file) => join(pkgDir(name), file);
const pkgVersion = (name) => JSON.parse(readFileSync(pkgFile(name, "package.json"), "utf8")).version;

// 1. Arabic: KFGQPC Hafs, rendered with its waqf marks.
const mushaf = await Mushaf.hafs();
const hafsJson = JSON.parse(readFileSync(pkgFile("@quran.ws/text", "data/hafs.json"), "utf8"));
const arabic = [];
const surahs = [];
const enMeta = JSON.parse(readFileSync(pkgFile("quran-json", "dist/quran_en.json"), "utf8"));
for (let s = 1; s <= 114; s++) {
  const surah = mushaf.surah(s);
  const verses = [];
  for (let a = 1; a <= surah.ayahCount; a++) verses.push(mushaf.ayah(s, a).render({ marks: true }));
  arabic.push(verses);
  surahs.push({
    number: s,
    nameArabic: surah.nameAr,
    nameTransliterated: surah.nameEn,
    nameMeaning: enMeta[s - 1].translation,
    revelation: surah.revelation === "makki" ? "Meccan" : "Medinan",
    ayahCount: surah.ayahCount,
  });
}

// 2. English: Saheeh International, verbatim from quran-db.
const saheehPath = pkgFile("quran-db", "utils/translations/en_saheeh.js");
const saheehRows = (await import(pathToFileURL(saheehPath).href)).default;
const english = surahs.map((s) => new Array(s.ayahCount).fill(null));
for (const row of saheehRows) english[row.surah_number - 1][row.verse_number - 1] = row.content;

// 3. Cross-checks against independent copies. Any mismatch stops the import.
const problems = [];
if (arabic.flat().length !== meta.numAyahs) problems.push(`Arabic has ${arabic.flat().length} ayahs, expected ${meta.numAyahs}`);
const qjArabic = JSON.parse(readFileSync(pkgFile("quran-json", "dist/quran.json"), "utf8"));
for (let s = 1; s <= 114; s++) {
  const expected = getSurahMeta(s).ayahCount;
  if (arabic[s - 1].length !== expected) problems.push(`Surah ${s}: ${arabic[s - 1].length} ayahs, quran-meta says ${expected}`);
  qjArabic[s - 1].verses.forEach((v, i) => {
    if (skeleton(v.text) !== skeleton(arabic[s - 1][i] ?? "")) problems.push(`Arabic ${s}:${i + 1} letters differ from QuranEnc copy`);
  });
  enMeta[s - 1].verses.forEach((v, i) => {
    const ours = english[s - 1][i];
    if (ours == null) problems.push(`English ${s}:${i + 1} missing`);
    else if (stripEndPunctuation(ours) !== stripEndPunctuation(v.translation)) problems.push(`English ${s}:${i + 1} differs from QuranEnc copy`);
  });
}
if (problems.length) {
  console.error(problems.slice(0, 40).join("\n"));
  console.error(`${problems.length} problems; nothing written.`);
  process.exit(1);
}

// 4. Write files and the manifest that pins them.
const write = (name, data) => {
  const text = JSON.stringify(data) + "\n";
  writeFileSync(join(out, name), text);
  return createHash("sha256").update(text).digest("hex");
};
const arabicSha = write("arabic-hafs.json", arabic);
const englishSha = write("translation-en-saheeh.json", english);
const surahsSha = write("surahs.json", surahs);

const manifest = {
  importedAt: new Date().toISOString().slice(0, 10),
  readOnly: true,
  note: "Generated by scripts/import-quran.mjs. Do not edit these files by hand; re-run the import instead.",
  files: {
    "arabic-hafs.json": {
      sha256: arabicSha,
      kind: "arabic",
      title: "Quran text, Hafs an Asim, KFGQPC Uthmanic Hafs v3.0",
      publisher: "King Fahd Glorious Quran Printing Complex (KFGQPC), Madinah",
      via: `npm @quran.ws/text@${pkgVersion("@quran.ws/text")} (CC BY 4.0 packaging)`,
      upstreamSha256: hafsJson.provenance.text.sha256,
      ayahCount: arabic.flat().length,
      crossCheckedAgainst: `npm quran-json@${pkgVersion("quran-json")} (QuranEnc Uthmani text): letters of every ayah match`,
      font: "Amiri Quran (SIL Open Font License), which covers every codepoint in this text",
      licenceStatus: "Text reproduced verbatim with attribution to KFGQPC. The KFGQPC font itself is not bundled because its licence forbids redistribution without written approval.",
    },
    "translation-en-saheeh.json": {
      sha256: englishSha,
      kind: "translation",
      title: "Saheeh International English translation",
      publisher: "Saheeh International (Dar Abul-Qasim)",
      via: `npm quran-db@${pkgVersion("quran-db")}`,
      crossCheckedAgainst: `npm quran-json@${pkgVersion("quran-json")} (QuranEnc copy): every verse matches apart from final punctuation, which that copy strips`,
      licenceStatus: "Copyrighted translation. QuranEnc permits verbatim republication with credit; obtain written permission from the publisher before a commercial release.",
    },
    "surahs.json": {
      sha256: surahsSha,
      kind: "metadata",
      title: "Surah names and ayah counts",
      via: `@quran.ws/text@${pkgVersion("@quran.ws/text")}; name meanings from quran-json@${pkgVersion("quran-json")}`,
      crossCheckedAgainst: `quran-meta@${pkgVersion("quran-meta")} ayah counts`,
    },
  },
};
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`Imported ${arabic.flat().length} ayahs in 114 surahs; cross-checks passed.`);
