  storyTitle: { fontFamily: fonts.display, fontSize: 21, color: colors.ink },
  status: { fontFamily: fonts.bodyBold, fontSize: 15, color: colors.greenDeep },
  sub: { fontFamily: fonts.bodyBold, fontSize: 14, color: colors.terracotta, marginTop: 8, textTransform: 'uppercase', letterSpacing: 0.5 },
  listItem: { fontSize: 15, lineHeight: 22 },
  small: { fontFamily: fonts.body, fontSize: 14, color: colors.inkSoft, lineHeight: 20 },
